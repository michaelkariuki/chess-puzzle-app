import { Chess } from 'chess.js';

import { parseUci } from '@/src/chess/uci';
import type { Puzzle } from '@/src/chess/types';
import seed from './seed-puzzles.json';

/**
 * The bundled seed set is the app's guarantee that it works offline, so it is
 * worth asserting it's actually playable. An earlier version of the generator
 * silently produced puzzles with no `fen` at all — which typechecked, shipped,
 * and would only have failed at render time.
 */
const puzzles = seed as Puzzle[];

describe('bundled seed puzzles', () => {
  it('is not empty', () => {
    expect(puzzles.length).toBeGreaterThan(0);
  });

  // Looped rather than it.each: the seed file is regenerated by a script, and
  // it.each throws outright on an empty table, which would mask the far more
  // useful "is not empty" failure above.
  it('every puzzle is well-formed', () => {
    const malformed = puzzles.filter(
      (p) =>
        typeof p.fen !== 'string' ||
        p.fen.length === 0 ||
        !Array.isArray(p.solution) ||
        p.solution.length === 0 ||
        typeof p.rating !== 'number',
    );
    expect(malformed.map((p) => p.id)).toEqual([]);
  });

  it('every solution line is fully legal from its starting position', () => {
    const broken: string[] = [];

    for (const puzzle of puzzles) {
      try {
        const chess = new Chess(puzzle.fen);
        for (const uci of puzzle.solution) {
          const parsed = parseUci(uci);
          if (!parsed) throw new Error(`unparseable move ${uci}`);
          chess.move({ from: parsed.from, to: parsed.to, promotion: parsed.promotion });
        }
      } catch (err) {
        broken.push(`${puzzle.id}: ${err instanceof Error ? err.message : 'failed'}`);
      }
    }

    expect(broken).toEqual([]);
  });

  /**
   * The sharp check. Legality alone does NOT catch an off-by-one in move
   * semantics: the Lichess bulk CSV starts its move list with the *opponent's*
   * setup move, while the API's fen already has the solver to move. Import the
   * CSV without dropping that first move and every line is still perfectly
   * legal — the player is just being asked to play the wrong side's move.
   *
   * A mateInN puzzle must end in checkmate delivered by the solver. That
   * pins down both the parity and the direction.
   */
  it('mate puzzles actually end in checkmate by the solver', () => {
    const mates = puzzles.filter((p) => p.themes.some((t) => /^mateIn\d+$/.test(t)));
    const broken: string[] = [];

    for (const puzzle of mates) {
      const chess = new Chess(puzzle.fen);
      const solver = chess.turn();

      for (const uci of puzzle.solution) {
        const parsed = parseUci(uci);
        if (!parsed) break;
        try {
          chess.move({ from: parsed.from, to: parsed.to, promotion: parsed.promotion });
        } catch {
          break;
        }
      }

      if (!chess.isCheckmate()) {
        broken.push(`${puzzle.id}: line does not end in mate`);
      } else if (chess.turn() === solver) {
        // Mated side is the one to move — that must be the opponent.
        broken.push(`${puzzle.id}: solver is the one mated (move parity is off)`);
      }
    }

    expect(broken).toEqual([]);
  });
});

describe('setup positions for the opening animation', () => {
  it('every puzzle carries a setup position', () => {
    const missing = puzzles.filter((p) => !p.setupFen).map((p) => p.id);
    expect(missing).toEqual([]);
  });

  it('every puzzle carries the setup move', () => {
    const missing = puzzles.filter((p) => !p.lastMove).map((p) => p.id);
    expect(missing).toEqual([]);
  });

  /**
   * The load animation plays `lastMove` from `setupFen`. If that move isn't
   * legal there, or doesn't land on the puzzle position, the board would jump
   * rather than slide — and the player would see a position that never existed.
   */
  it('playing lastMove from setupFen reproduces the puzzle position', () => {
    const broken: string[] = [];

    for (const puzzle of puzzles) {
      if (!puzzle.setupFen || !puzzle.lastMove) continue;
      const parsed = parseUci(puzzle.lastMove);
      if (!parsed) {
        broken.push(`${puzzle.id}: unparseable lastMove ${puzzle.lastMove}`);
        continue;
      }
      try {
        const chess = new Chess(puzzle.setupFen);
        chess.move({ from: parsed.from, to: parsed.to, promotion: parsed.promotion });
        // Compare placement/turn/castling/en-passant only — Lichess normalises
        // the move counters, and nothing in a puzzle depends on them.
        const got = chess.fen().split(' ').slice(0, 4).join(' ');
        const want = puzzle.fen.split(' ').slice(0, 4).join(' ');
        if (got !== want) broken.push(`${puzzle.id}: lands on ${got}, expected ${want}`);
      } catch {
        broken.push(`${puzzle.id}: lastMove ${puzzle.lastMove} is illegal from setupFen`);
      }
    }

    expect(broken).toEqual([]);
  });

  it('the setup position has the OPPONENT to move', () => {
    const wrongSide = puzzles
      .filter((p) => p.setupFen)
      .filter((p) => new Chess(p.setupFen!).turn() === new Chess(p.fen).turn())
      .map((p) => p.id);
    expect(wrongSide).toEqual([]);
  });
});
